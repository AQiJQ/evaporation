    global_step = 0
    best_eval_return_per_step = float(initial_stat["return_per_step"])
    best_eval_episode = 0
    best_design = copy.deepcopy(design)
    policy_candidates: list[dict[str, object]] = [{
        "episode": 0,
        "online_return_per_step": float(initial_stat["return_per_step"]),
        "actor_state": copy.deepcopy(agent.actor.state_dict()),
        "zero_fallback": True,
    }]
    agent.save_actor(model_dir / "best_actor.pth")
    agent.save_checkpoint(model_dir / "best_checkpoint.pth")
    save_theta_design(model_dir / "initial_theta.npz", initial_fixed_design)
    save_theta_design(model_dir / "optimized_theta.npz", optimized_fixed_design)
    save_theta_design(model_dir / "best_theta.npz", best_design)
    print(
        "episode=000/"
        f"{cfg.episodes} eval_per_step={initial_stat['return_per_step']:.6f} "
        f"economic_cost={initial_stat['economic_cost_mean']:.3f}",
        flush=True,
    )
    start = time.time()
    for episode in range(1, cfg.episodes + 1):
        stat, _, global_step = run_episode(
            cfg,
            model,
            controller,
            agent,
            replay,
            rng,
            training=True,
            global_step=global_step,
            theta_learner=theta_learner,
        )
        agent.update_actor_ema()
        if cfg.experiment_mode == "joint_theta":
            design, theta_metrics = theta_learner.update_after_episode(
                episode, design, design_evaluator=evaluate_continuous_k
            )
            controller = SafeController(cfg, model, design)
        else:
            # Transitions are retained for diagnostics, but the optimized
            # H-infinity/RPI/QP design is immutable throughout SAC training.
            theta_metrics = theta_learner.metrics(design)

        eval_return = float("nan")
        eval_return_per_step = float("nan")
        eval_economic_cost_mean = float("nan")
        eval_theta_only_cost = float("nan")
        eval_sac_cost = float("nan")
        eval_cost_reduction = float("nan")
        eval_safe_gap = float("nan")
        if (
            episode == 1
            or episode % cfg.evaluation_every == 0
            or episode == cfg.episodes
        ):
            eval_stat, _, _ = evaluate_policy(
                cfg, model, design, agent, evaluation_seeds
            )
            eval_return = float(eval_stat["return"])
            eval_return_per_step = float(eval_stat["return_per_step"])
            eval_economic_cost_mean = float(eval_stat["economic_cost_mean"])
            eval_baseline_stat, _, _ = evaluate_policy(
                cfg, model, design, no_rl_policy, evaluation_seeds
            )
            eval_theta_only_cost = float(eval_baseline_stat["economic_cost_mean"])
            eval_sac_cost = eval_economic_cost_mean
            eval_cost_reduction, eval_safe_gap = _paired_economic_metrics(
                eval_baseline_stat, eval_stat, safe_reference_cost
            )
            eval_safe = hard_safety_passed(eval_stat)
            policy_candidates.append({
                "episode": int(episode),
                "online_return_per_step": eval_return_per_step,
                "actor_state": copy.deepcopy(agent.actor.state_dict()),
                "zero_fallback": False,
            })
            if eval_safe and eval_return_per_step > best_eval_return_per_step:
                best_eval_return_per_step = eval_return_per_step
                best_eval_episode = episode
                best_design = copy.deepcopy(design)
                agent.save_actor(model_dir / "best_actor.pth")
                agent.save_checkpoint(model_dir / "best_checkpoint.pth")
                save_theta_design(model_dir / "best_theta.npz", best_design)

        if episode % cfg.save_every == 0 or episode == cfg.episodes:
            agent.save_actor(model_dir / "last_actor.pth")
            agent.save_checkpoint(model_dir / "last_checkpoint.pth")
            save_theta_design(model_dir / "last_theta.npz", design)

        logs.append({
            "episode": episode,
            **stat,
            **theta_metrics,
            "evaluation_return": eval_return,
            "evaluation_return_per_step": eval_return_per_step,
            "evaluation_economic_cost_mean": eval_economic_cost_mean,
            "evaluation_theta_only_economic_cost_mean": eval_theta_only_cost,
            "evaluation_safe_sac_economic_cost_mean": eval_sac_cost,
            "evaluation_sac_incremental_cost_reduction_percent": eval_cost_reduction,
            "evaluation_normalized_safe_performance_gap": eval_safe_gap,
            "safe_reference_cost": safe_reference_cost,
        })
        if episode == 1 or episode % 10 == 0:
            eval_text = (
                f" eval_cost={eval_economic_cost_mean:.3f}"
                if np.isfinite(eval_economic_cost_mean) else ""
            )
            print(
                f"episode={episode:03d}/{cfg.episodes} "
                f"return={stat['return']:.3f} "
                f"per_step={stat['return_per_step']:.4f} "
                f"violation={stat['violation_rate']:.4f} "
                f"rpi={stat['rpi_violation_rate']:.4f} "
                f"intervention={stat['intervention_rate']:.3f} "
                f"alpha={stat['alpha']:.4f}"
                f" M_updates={int(theta_metrics['theta_set_update_accepts'])}"
                f" K_updates={int(theta_metrics['theta_K_update_accepts'])}"
                f"{eval_text}",
                flush=True,
            )

    # Preserve and assess the raw final actor before final-data certification.
    last_stat, _, _ = evaluate_policy(
        cfg, model, design, agent, evaluation_seeds
    )
    holdout_seeds = [
        cfg.seed + 20000 + index for index in range(cfg.holdout_seed_count)
    ]
    holdout_last_stat, _, _ = evaluate_policy(
        cfg, model, design, agent, holdout_seeds
    )
    training_gradient_updates = int(agent.total_updates)

    # The joint-theta ablation rebuilds against its final hull.  The proposed
    # mode deliberately keeps the offline design fixed and only audits newly
    # observed residuals against it.
    final_data_hull = np.asarray(theta_learner.data_hull, dtype=float).copy()
    if cfg.experiment_mode == "joint_theta":
        design = build_safety_design(
            cfg,
            model,
            np.random.default_rng(cfg.seed + 51001),
            w_data_hull=final_data_hull,
            theta_m_angle=design.theta_m_angle,
            theta_h=design.theta_h,
            theta_p=design.theta_p,
            theta_k=design.k,
        )
    uncovered_final_vertices = sum(
        not point_in_convex_polygon(point, design.w_vertices, tol=1e-8)
        for point in final_data_hull
    )
    if uncovered_final_vertices and cfg.experiment_mode == "joint_theta":
        raise RuntimeError(
            "Final safety design does not contain every retained disturbance "
            f"vertex ({uncovered_final_vertices} uncovered)."
        )
    if uncovered_final_vertices and cfg.experiment_mode == "proposed":
        print(
            "WARNING: fixed proposed safety design did not contain all observed "
            f"effective-disturbance hull vertices ({uncovered_final_vertices}); "
            "final certification will be marked failed.",
            flush=True,
        )

    # Select the SAC policy only after all candidates have been placed behind
    # the same final certified theta.  The paired zero-residual result is a
    # hard lower-performance gate; scale=0 remains an honest safe fallback.
    theta_only_stat, theta_only_records, _ = evaluate_policy(
        cfg, model, design, no_rl_policy, evaluation_seeds
    )
    # Every periodic evaluation checkpoint is audited.  Prescreening by shaped
    # training return would incorrectly discard economically better policies.
    ranked_candidates = list(policy_candidates)

    selected_candidate: dict[str, object] | None = None
    candidate_audit: list[dict[str, float]] = []
    for candidate in ranked_candidates:
        agent.actor.load_state_dict(candidate["actor_state"])
        agent.actor_ema.load_state_dict(candidate["actor_state"])
        candidate_scales = (
            (0.0,)
            if bool(candidate.get("zero_fallback", False))
            else tuple(cfg.sac_selection_scales)
        )
        for policy_scale in candidate_scales:
            agent.set_policy_output_scale(policy_scale)
            candidate_stat, _, _ = evaluate_policy(
                cfg, model, design, agent, evaluation_seeds
            )
            incremental_return = float(
                candidate_stat["return_per_step"]
                - theta_only_stat["return_per_step"]
            )
            safe = hard_safety_passed(candidate_stat)
            positive_increment = economic_policy_eligible(
                candidate_stat,
                float(theta_only_stat["economic_cost_mean"]),
                float(policy_scale),
            )
            zero_fallback = bool(
                policy_scale == 0.0 and candidate.get("zero_fallback", False)
            )
            eligible = bool(zero_fallback or positive_increment)
            cost_reduction_percent = float(
                100.0
                * (theta_only_stat["economic_cost_mean"] - candidate_stat["economic_cost_mean"])
                / max(abs(theta_only_stat["economic_cost_mean"]), 1e-12)
            )
            practically_significant = bool(
                positive_increment
                and cost_reduction_percent
                >= float(cfg.sac_min_economic_improvement_percent) - 1e-12
            )
            # Always retain an honest scale=0 diagnostic fallback.  It is not
            # mislabeled as certified when the fixed design itself is violated.
            eligible = bool(zero_fallback or (safe and eligible))
            audit_row = {
                "episode": float(candidate["episode"]),
                "policy_scale": float(policy_scale),
                "return_per_step": float(candidate_stat["return_per_step"]),
                "economic_cost_mean": float(candidate_stat["economic_cost_mean"]),
                "incremental_return_per_step": incremental_return,
                "economic_cost_reduction_percent": cost_reduction_percent,
                "violation_rate": float(candidate_stat["violation_rate"]),
                "rpi_violation_rate": float(candidate_stat["rpi_violation_rate"]),
                "qp_infeasible_rate": float(candidate_stat["qp_infeasible_rate"]),
                "disturbance_bound_exceedance_rate": float(
                    candidate_stat["disturbance_bound_exceedance_rate"]
                ),
                "intervention_rate": float(candidate_stat["intervention_rate"]),
                "mapping_rate": float(candidate_stat["feasible_action_mapping_rate"]),
                "safe": float(safe),
                "positive_increment": float(positive_increment),
                "practically_significant": float(practically_significant),
                "eligible": float(eligible),
            }
            candidate_audit.append(audit_row)
            if eligible and (
                selected_candidate is None
                or (
                    audit_row["economic_cost_mean"],
                    -audit_row["return_per_step"],
                    audit_row["intervention_rate"],
                )
                < (
                    float(selected_candidate["economic_cost_mean"]),
                    -float(selected_candidate["return_per_step"]),
                    float(selected_candidate["intervention_rate"]),
                )
            ):
                selected_candidate = {
                    **audit_row,
                    "actor_state": copy.deepcopy(candidate["actor_state"]),
                }

    if selected_candidate is None:
        raise RuntimeError(
            "No final-data-certified policy passed the paired theta-only gate."
        )
    agent.actor.load_state_dict(selected_candidate["actor_state"])
    agent.actor_ema.load_state_dict(selected_candidate["actor_state"])
    agent.set_policy_output_scale(float(selected_candidate["policy_scale"]))
    best_eval_episode = int(selected_candidate["episode"])
    best_eval_return_per_step = float(selected_candidate["return_per_step"])
    best_design = copy.deepcopy(design)
    agent.save_actor(model_dir / "best_actor.pth")
    agent.save_checkpoint(model_dir / "best_checkpoint.pth")
    save_theta_design(model_dir / "best_theta.npz", design)
    save_csv(
        cfg.output_dir / "final_checkpoint_audit.csv",
        list(candidate_audit[0].keys()),
        ([row[key] for key in candidate_audit[0]] for row in candidate_audit),
    )

    final_stat, final_records, _ = evaluate_policy(
        cfg, model, design, agent, evaluation_seeds
    )
    holdout_best_stat, _, _ = evaluate_policy(
        cfg, model, design, agent, holdout_seeds
    )

    # Two controlled ablations on paired seeds:
    # (1) learned theta with the SAC residual removed; and
    # (2) fixed initial theta with no SAC, which is the true no-learning case.
    holdout_theta_only_stat, _, _ = evaluate_policy(
        cfg, model, design, no_rl_policy, holdout_seeds
    )
    no_rl_stat, no_rl_records, _ = evaluate_policy(
        cfg, model, initial_fixed_design, no_rl_policy, evaluation_seeds
    )
    holdout_no_rl_stat, _, _ = evaluate_policy(
        cfg, model, initial_fixed_design, no_rl_policy, holdout_seeds
    )
    nonzero_audit = [
        row for row in candidate_audit if float(row["policy_scale"]) > 0.0
    ]
    best_nonzero = min(
        nonzero_audit,
        key=lambda row: (
            float(row["economic_cost_mean"]),
            float(row["violation_rate"]),
            float(row["intervention_rate"]),
        ),
        default=None,
    )

    rollout = records_to_arrays(final_records)
    theta_only_rollout = records_to_arrays(theta_only_records)
    no_rl_rollout = records_to_arrays(no_rl_records)
    log_arrays = {
        key: np.asarray([row[key] for row in logs], dtype=float)
        for key in logs[0]
    }
    save_csv(
        cfg.output_dir / "training_log.csv",
        list(logs[0].keys()),
        ([row[key] for key in logs[0]] for row in logs),
    )
    eval_mask = np.isfinite(log_arrays["evaluation_return_per_step"])
    eval_episodes = log_arrays["episode"][eval_mask]
    eval_values = log_arrays["evaluation_return_per_step"][eval_mask]
    eval_best_so_far = np.maximum.accumulate(eval_values)
    eval_best = float(np.max(eval_values))
    eval_scale = max(eval_best - float(eval_values[0]), 1e-12)
    empirical_regret = (eval_best_so_far - eval_best) / eval_scale
    save_csv(
        cfg.output_dir / "empirical_regret.csv",
        [
            "episode",
            "evaluation_return_per_step",
            "best_so_far_return_per_step",
            "normalized_empirical_regret",
        ],
        zip(eval_episodes, eval_values, eval_best_so_far, empirical_regret),
    )
    save_rollout_csv(cfg.output_dir / "evaluation_rollout.csv", rollout)
    save_rollout_csv(cfg.output_dir / "theta_only_rollout.csv", theta_only_rollout)
    save_rollout_csv(cfg.output_dir / "no_rl_rollout.csv", no_rl_rollout)
    np.savez_compressed(
        cfg.output_dir / "safety_design.npz",
        A=design.a,
        B=design.b,
        affine=design.affine,
        K=design.k,
        h=design.theta_h,
        p=design.theta_p,
        M=design.theta_m_matrix,
        m=design.theta_m_bound,
        W=design.w_bound,
        disturbance_vertices=design.w_vertices,
        disturbance_data_hull=design.w_data_hull,
        rpi_boundary=design.rpi_boundary,
        rpi_support=design.rpi_support,
        rpi_support_lower=design.rpi_support_lower,
        rpi_support_upper=design.rpi_support_upper,
        box_reference_rpi_width_physical=design.box_reference_rpi_width_physical,
        box_reference_rpi_area_physical=design.box_reference_rpi_area_physical,
        invariant_lower=design.invariant_lower,
        invariant_upper=design.invariant_upper,
        invariant_scale=design.invariant_scale,
        gain_state_weight_scale=design.gain_state_weight_scale,
        gain_input_weight_scale=design.gain_input_weight_scale,
    )

    boundary = design.rpi_boundary
    rpi_physical = cfg.safe_center_state + boundary * cfg.state_scale
    rpi_area = 0.5 * abs(float(np.sum(
        rpi_physical[:, 0] * np.roll(rpi_physical[:, 1], -1)
        - rpi_physical[:, 1] * np.roll(rpi_physical[:, 0], -1)
    )))
    initial_rpi_physical = (
        cfg.safe_center_state
        + initial_fixed_design.rpi_boundary * cfg.state_scale
    )
    initial_rpi_area = 0.5 * abs(float(np.sum(
        initial_rpi_physical[:, 0] * np.roll(initial_rpi_physical[:, 1], -1)
        - initial_rpi_physical[:, 1] * np.roll(initial_rpi_physical[:, 0], -1)
    )))
    x_minus_z_width = (
        design.x_upper_tight - design.x_lower_tight
    ) * cfg.state_scale
    initial_x_minus_z_width = (
        initial_fixed_design.x_upper_tight
        - initial_fixed_design.x_lower_tight
    ) * cfg.state_scale
    invariant_width = (
        design.invariant_upper - design.invariant_lower
    ) * cfg.state_scale
    initial_invariant_width = (
        initial_fixed_design.invariant_upper - initial_fixed_design.invariant_lower
    ) * cfg.state_scale
    peak_w_positive = np.max(rollout["effective_w"], axis=0)
    peak_w_negative = -np.min(rollout["effective_w"], axis=0)
    training_mask = log_arrays["episode"] >= 1.0
    training_returns = log_arrays["return"][training_mask]
    nominal_economic_reference_cost = model.economic_cost(
        cfg.linearization_state,
        cfg.linearization_input,
        cfg.disturbance_nominal,
    )
    safe_center_input = model.physical_input(design.v_ref)
    safe_center_cost = model.economic_cost(
        cfg.safe_center_state,
        safe_center_input,
        cfg.disturbance_nominal,
    )
    state_constraint_area = float(np.prod(cfg.state_upper - cfg.state_lower))
    initial_x_minus_z_area = float(np.prod(initial_x_minus_z_width))
    optimized_x_minus_z_area = float(np.prod(x_minus_z_width))
    initial_invariant_area = float(np.prod(initial_invariant_width))
    optimized_invariant_area = float(np.prod(invariant_width))
    final_cost_reduction, final_safe_gap = _paired_economic_metrics(
        theta_only_stat, final_stat, safe_reference_cost
    )
    holdout_cost_reduction, _ = _paired_economic_metrics(
        holdout_theta_only_stat, holdout_best_stat, safe_reference_cost
    )
    feedback_law = save_feedback_law(
        cfg, design, cfg.output_dir, agent.policy_output_scale
    )
    final_theta_metrics = theta_learner.metrics(design)
    policy_map = evaluate_sac_policy_map(cfg, model, design, agent)
    requested_map = policy_map["requested_physical"]
