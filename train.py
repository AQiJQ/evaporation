OBS_DIM = 19
ACTION_DIM = 2


class ZeroResidualPolicy:
    """No-RL ablation: retain H-infinity/RPI/QP and set SAC residual to zero."""

    alpha = 0.0

    @staticmethod
    def select_action(obs: np.ndarray, deterministic: bool = True) -> np.ndarray:
        del obs, deterministic
        return np.zeros(ACTION_DIM, dtype=np.float32)


def observation(
    model: EvaporatorModel,
    controller: SafeController,
    state: np.ndarray,
    previous_u: np.ndarray,
    disturbance_estimate: np.ndarray | None = None,
) -> np.ndarray:
    """Plant feedback plus known controller context; disturbance stays hidden.

    The slow theta/K learner changes the closed-loop transition kernel during
    training.  Supplying its normalized current values prevents replay from
    aliasing transitions generated by different controllers as the same SAC
    state.  These are internal controller parameters, not plant disturbances.
    """
    x = model.normalized_state(state)
    e = x - controller.z
    design = controller.d
    k_scale = np.array([[12.0, 3.0], [1.0, 3.0]], dtype=float)
    parameter_clip = max(float(model.cfg.theta_parameter_clip), 1e-12)
    angle_limit = max(
        np.deg2rad(float(model.cfg.theta_m_max_angle_degrees)), 1e-12
    )
    controller_context = np.concatenate([
        design.k.ravel() / k_scale.ravel(),
        design.theta_h / parameter_clip,
        design.theta_p / parameter_clip,
        [design.theta_m_angle / angle_limit],
    ])
    w_est = (
        np.zeros(2, dtype=float)
        if disturbance_estimate is None
        else np.asarray(disturbance_estimate, dtype=float)
    )
    normalized_w_est = w_est / np.maximum(design.w_bound, 1e-12)
    return np.clip(
        np.concatenate([
            x - controller.d.z_ref,
            e,
            previous_u - controller.d.v_ref,
            controller_context,
            normalized_w_est,
        ]),
        -4.0,
        4.0,
    ).astype(np.float32)


def sample_disturbance(cfg: ExperimentConfig, rng: np.random.Generator) -> np.ndarray:
    """Draw the four bounded feed/temperature disturbances from the paper."""
    return rng.uniform(
        cfg.disturbance_nominal - cfg.disturbance_half_range,
        cfg.disturbance_nominal + cfg.disturbance_half_range,
    )


def advance_disturbance(
    cfg: ExperimentConfig,
    rng: np.random.Generator,
    current: np.ndarray,
    completed_steps: int,
) -> np.ndarray:
    """Advance the configured bounded hidden-disturbance process."""
    if cfg.disturbance_mode == "iid":
        return sample_disturbance(cfg, rng)
    if cfg.disturbance_mode != "piecewise_constant":
        raise ValueError("disturbance_mode must be 'iid' or 'piecewise_constant'")
    hold = int(cfg.disturbance_hold_steps)
    if hold <= 0:
        raise ValueError("disturbance_hold_steps must be positive")
    if completed_steps % hold == 0:
        return sample_disturbance(cfg, rng)
    return np.asarray(current, dtype=float).copy()


def run_episode(
    cfg: ExperimentConfig,
    model: EvaporatorModel,
    controller: SafeController,
    agent,
    replay: ReplayBuffer,
    rng: np.random.Generator,
    *,
    training: bool,
    global_step: int,
    theta_learner: OnlineThetaLearner | None = None,
) -> tuple[dict[str, float], list[dict[str, object]], int]:
    initial_fraction = (
        cfg.training_initial_radius_fraction
        if training else cfg.evaluation_initial_radius_fraction
    )
    initial_lower = controller.d.z_ref + initial_fraction * (
        controller.d.invariant_lower - controller.d.z_ref
    )
    initial_upper = controller.d.z_ref + initial_fraction * (
        controller.d.invariant_upper - controller.d.z_ref
    )
    if cfg.reset_within_disturbance_identification_window:
        identified_lower = model.normalized_state(
            cfg.safe_center_state - cfg.theta_initial_safe_state_half_range
        )
        identified_upper = model.normalized_state(
            cfg.safe_center_state + cfg.theta_initial_safe_state_half_range
        )
        initial_lower = np.maximum(initial_lower, identified_lower)
        initial_upper = np.minimum(initial_upper, identified_upper)
        if np.any(initial_upper <= initial_lower):
            raise RuntimeError(
                "Disturbance-identified reset window does not intersect the "
                "controlled-invariant set."
            )
    def reset_segment():
        z0 = rng.uniform(initial_lower, initial_upper)
        if training and rng.random() < cfg.training_boundary_start_probability:
            boundary_axis = int(rng.integers(0, 2))
            z0[boundary_axis] = rng.choice([
                initial_lower[boundary_axis], initial_upper[boundary_axis]
            ])
        segment_state = model.physical_state(z0)
        controller.reset(segment_state)
        segment_previous_u = controller.d.v_ref.copy()
        segment_previous_residual = np.zeros(ACTION_DIM, dtype=float)
        segment_disturbance = sample_disturbance(cfg, rng)
        segment_w_est = np.zeros(2, dtype=float)
        segment_obs = observation(
            model,
            controller,
            segment_state,
            segment_previous_u,
            segment_w_est,
        )
        return (
            segment_state,
            segment_previous_u,
            segment_previous_residual,
            segment_disturbance,
            segment_w_est,
            0,
            segment_obs,
        )

    (
        state,
        previous_u,
        previous_applied_residual,
        disturbance,
        w_est,
        disturbance_age,
        obs,
    ) = reset_segment()
    reward_reference_cost = model.economic_cost(
        cfg.linearization_state,
        cfg.linearization_input,
        cfg.disturbance_nominal,
    )

    total_return = 0.0
    violations = 0
    rpi_violations = 0
    bound_exceedances = 0
    interventions = 0
    infeasible = 0
    economic_cost_sum = 0.0
    economic_reward_sum = 0.0
    projection_penalty_sum = 0.0
    mapping_penalty_sum = 0.0
    mapping_activations = 0
    move_penalty_sum = 0.0
    safety_penalty_sum = 0.0
    state_excess_squared_sum = 0.0
    input_excess_squared_sum = 0.0
    rpi_excess_squared_sum = 0.0
    rpi_utilization_peak = 0.0
    residual_feasible_scale_sum = 0.0
    residual_feasible_scale_min = 1.0
    residual_requested_norm_sum = 0.0
    residual_applied_norm_sum = 0.0
    residual_execution_ratio_sum = 0.0
    records: list[dict[str, object]] = []
    last_losses: dict[str, float] | None = None

    for step in range(cfg.steps_per_episode):
        if training and global_step < cfg.warmup_steps:
            raw_action = rng.uniform(-1.0, 1.0, ACTION_DIM).astype(np.float32)
        else:
            raw_action = agent.select_action(
                obs,
                deterministic=not training,
            ).astype(np.float32)

        # The critic stores the original continuous actor command in [-1,1]^2.
        # The environment maps it to a physical residual before the safety QP.
        control, info = controller.act(
            state, raw_action, action_is_normalized=True
        )
        residual = np.asarray(info["requested_residual"], dtype=float)
        next_state = model.step(state, control, disturbance)
        x_next_n = model.normalized_state(next_state)
        e_next = x_next_n - controller.z
        acl = controller.d.a + controller.d.b @ controller.d.k
        w_hat = x_next_n - (
            controller.d.a @ np.asarray(info["x_norm"])
            + controller.d.b @ np.asarray(info["actual_norm"])
            + controller.d.affine
        )
        effective_w = w_hat.copy()
        beta = float(cfg.disturbance_estimate_ema)
        if not 0.0 <= beta < 1.0:
            raise ValueError("disturbance_estimate_ema must be in [0, 1)")
        next_w_est = beta * w_est + (1.0 - beta) * w_hat

        state_bad = bool(
            np.any(next_state < cfg.state_lower - 1e-8)
            or np.any(next_state > cfg.state_upper + 1e-8)
        )
        input_bad = bool(
            np.any(control < cfg.input_lower - 1e-8)
            or np.any(control > cfg.input_upper + 1e-8)
        )
        rpi_bad = not point_in_convex_polygon(
            e_next, controller.d.rpi_boundary, tol=1e-8
        )
        bound_bad = not point_in_convex_polygon(
            effective_w, controller.d.w_vertices, tol=1e-8
        )
        violation = state_bad or input_bad
        projection = float(info["projection_gap"])
        mapping_scale = float(info["feasible_action_mapping_scale"])
        mapping_gap = float(info["feasible_action_mapping_gap"])
        applied_residual = np.asarray(info["nominal"]) - np.asarray(info["base"])
        requested_norm = float(np.linalg.norm(residual))
        applied_norm = float(np.linalg.norm(applied_residual))
        execution_ratio = applied_norm / max(requested_norm, 1e-12)
        # The ray mapper is now part of the declared action parameterization,
        # so its safe result is the action attributed to SAC.  Only an actual
        # QP fallback suppresses learning credit.
        execution_mask = float(info["qp_feasible"])
        cost = model.economic_cost(next_state, control, disturbance)
        if training and theta_learner is not None:
            theta_learner.observe_transition(
                state, control, next_state, cost, controller.d
            )
        economic_reward = (reward_reference_cost - cost) / cfg.reward_cost_scale
        state_excess = (
            np.maximum(cfg.state_lower - next_state, 0.0)
            + np.maximum(next_state - cfg.state_upper, 0.0)
        ) / cfg.state_scale
        input_excess = (
            np.maximum(cfg.input_lower - control, 0.0)
            + np.maximum(control - cfg.input_upper, 0.0)
        ) / cfg.input_scale
        rpi_ratio = np.where(
            e_next >= 0.0,
            e_next / np.maximum(controller.d.rpi_support_upper, 1e-12),
            -e_next / np.maximum(controller.d.rpi_support_lower, 1e-12),
        )
        rpi_excess = np.maximum(rpi_ratio - 1.0, 0.0)
        state_excess_squared = float(np.sum(state_excess ** 2))
        input_excess_squared = float(np.sum(input_excess ** 2))
        rpi_excess_squared = float(np.sum(rpi_excess ** 2))
        projection_penalty = cfg.projection_penalty_weight * projection ** 2
        mapping_penalty = (
            cfg.feasible_action_mapping_penalty_weight * mapping_gap ** 2
        )
        move_penalty = cfg.input_move_penalty_weight * float(
            np.sum((applied_residual - previous_applied_residual) ** 2)
        )
        safety_penalty = (
            cfg.state_violation_event_penalty * float(state_bad)
            + cfg.input_violation_event_penalty * float(input_bad)
            + cfg.rpi_violation_event_penalty * float(rpi_bad)
            + cfg.qp_infeasible_event_penalty * float(not info["qp_feasible"])
            + cfg.state_excess_square_weight * state_excess_squared
            + cfg.input_excess_square_weight * input_excess_squared
            + cfg.rpi_excess_square_weight * rpi_excess_squared
        )
        reward = (
            economic_reward - projection_penalty - mapping_penalty
            - move_penalty - safety_penalty
        )
        segment_done = bool(
            training
            and int(cfg.training_segment_steps) > 0
            and (step + 1) % int(cfg.training_segment_steps) == 0
        )
        done = bool(step == cfg.steps_per_episode - 1 or segment_done)
        next_disturbance = advance_disturbance(
            cfg, rng, disturbance, disturbance_age + 1
        )
        next_obs = observation(
            model,
            controller,
            next_state,
            np.asarray(info["actual_norm"]),
            next_w_est,
        )

        if training:
            replay.add(
                obs, raw_action, reward, next_obs, done,
                execution_mask=execution_mask,
            )
            # Match the CSTR-SAC warm-up order: random actions are retained
            # until warmup_steps, but learning begins as soon as one complete
            # replay minibatch exists.  The actor is therefore already trained
            # when it first takes control.
            if replay.size >= cfg.batch_size:
                for _ in range(cfg.updates_per_step):
                    last_losses = agent.update(replay, cfg.batch_size)

        violations += int(violation)
        rpi_violations += int(rpi_bad)
        bound_exceedances += int(bound_bad)
        interventions += int(projection > cfg.qp_intervention_tolerance)
        infeasible += int(not info["qp_feasible"])
        economic_cost_sum += cost
        economic_reward_sum += economic_reward
        projection_penalty_sum += projection_penalty
        mapping_penalty_sum += mapping_penalty
        mapping_activations += int(
            cfg.residual_parameterization == "legacy_ray"
            and mapping_scale < 1.0 - 1e-10
        )
        residual_feasible_scale_sum += mapping_scale
        residual_feasible_scale_min = min(residual_feasible_scale_min, mapping_scale)
        residual_requested_norm_sum += requested_norm
        residual_applied_norm_sum += applied_norm
        residual_execution_ratio_sum += execution_ratio
        move_penalty_sum += move_penalty
        safety_penalty_sum += safety_penalty
        state_excess_squared_sum += state_excess_squared
        input_excess_squared_sum += input_excess_squared
        rpi_excess_squared_sum += rpi_excess_squared
        rpi_utilization_peak = max(
            rpi_utilization_peak,
            float(np.max(rpi_ratio)),
        )
        total_return += reward
        records.append({
            "time": step * cfg.dt_min,
            "state": state.copy(),
            "control": control.copy(),
            "disturbance": disturbance.copy(),
            "raw_action": raw_action.copy(),
            "residual": residual.copy(),
            "applied_residual": applied_residual.copy(),
            "w_hat": w_hat.copy(),
            "w_est": next_w_est.copy(),
            "residual_feasible_scale": mapping_scale,
            "residual_requested_norm": requested_norm,
            "residual_applied_norm": applied_norm,
            "residual_execution_ratio": execution_ratio,
            "execution_mask": execution_mask,
            "feasible_action_mapping_scale": mapping_scale,
            "feasible_action_mapping_gap": mapping_gap,
            "base": np.asarray(info["base"]).copy(),
            "nominal_control": np.asarray(info["nominal"]).copy(),
            "ancillary": np.asarray(info["ancillary"]).copy(),
            "reward": reward,
            "economic_cost": cost,
            "economic_reward": economic_reward,
            "projection_penalty": projection_penalty,
            "mapping_penalty": mapping_penalty,
            "move_penalty": move_penalty,
            "safety_penalty": safety_penalty,
            "state_excess_squared": state_excess_squared,
            "input_excess_squared": input_excess_squared,
            "rpi_excess_squared": rpi_excess_squared,
            "violation": violation,
            "rpi_violation": rpi_bad,
            "projection_gap": projection,
            "candidate": np.asarray(info["candidate"]).copy(),
            "nominal": np.asarray(info["nominal"]).copy(),
            "error": e_next.copy(),
            "effective_w": effective_w.copy(),
        })
        if segment_done and step < cfg.steps_per_episode - 1:
            (
                state,
                previous_u,
                previous_applied_residual,
                disturbance,
                w_est,
                disturbance_age,
                obs,
            ) = reset_segment()
        else:
            state = next_state
            obs = next_obs
            disturbance = next_disturbance
            w_est = next_w_est
            disturbance_age += 1
            previous_u = np.asarray(info["actual_norm"])
            previous_applied_residual = applied_residual
        global_step += 1

    q_loss = float("nan")
    actor_loss = float("nan")
    entropy = float("nan")
    if last_losses:
        q_loss = 0.5 * (
            float(last_losses["q1_loss"]) + float(last_losses["q2_loss"])
        )
        actor_loss = float(last_losses["actor_loss"])
        entropy = -float(last_losses["mean_logp"])
    stats = {
        "return": total_return,
        "return_per_step": total_return / cfg.steps_per_episode,
        "economic_cost_mean": economic_cost_sum / cfg.steps_per_episode,
        "economic_reward_mean": economic_reward_sum / cfg.steps_per_episode,
        "projection_penalty_mean": projection_penalty_sum / cfg.steps_per_episode,
        "mapping_penalty_mean": mapping_penalty_sum / cfg.steps_per_episode,
        "feasible_action_mapping_rate": mapping_activations / cfg.steps_per_episode,
        "residual_feasible_scale_mean": (
            residual_feasible_scale_sum / cfg.steps_per_episode
        ),
        "residual_feasible_scale_min": residual_feasible_scale_min,
        "residual_requested_norm_mean": (
            residual_requested_norm_sum / cfg.steps_per_episode
        ),
        "residual_applied_norm_mean": (
            residual_applied_norm_sum / cfg.steps_per_episode
        ),
        "residual_execution_ratio_mean": (
            residual_execution_ratio_sum / cfg.steps_per_episode
        ),
        "move_penalty_mean": move_penalty_sum / cfg.steps_per_episode,
        "safety_penalty_mean": safety_penalty_sum / cfg.steps_per_episode,
        "state_excess_squared_mean": (
            state_excess_squared_sum / cfg.steps_per_episode
        ),
        "input_excess_squared_mean": (
            input_excess_squared_sum / cfg.steps_per_episode
        ),
        "rpi_excess_squared_mean": (
            rpi_excess_squared_sum / cfg.steps_per_episode
        ),
        "violation_rate": violations / cfg.steps_per_episode,
        "rpi_violation_rate": rpi_violations / cfg.steps_per_episode,
        "disturbance_bound_exceedance_rate": (
            bound_exceedances / cfg.steps_per_episode
        ),
        "intervention_rate": interventions / cfg.steps_per_episode,
        "qp_infeasible_rate": infeasible / cfg.steps_per_episode,
        "rpi_utilization_peak": rpi_utilization_peak,
        "alpha": float(getattr(agent, "alpha", 0.0)),
        "entropy": entropy,
        "q_loss": q_loss,
        "actor_loss": actor_loss,
        "execution_mask_mean": float(np.mean([
            record["execution_mask"] for record in records
        ])),
    }
    return stats, records, global_step


def records_to_arrays(records: list[dict[str, object]]) -> dict[str, np.ndarray]:
    keys = [
        "time", "state", "control", "disturbance", "raw_action", "residual",
        "applied_residual", "w_hat", "w_est",
        "residual_feasible_scale", "residual_requested_norm",
        "residual_applied_norm", "residual_execution_ratio", "execution_mask",
        "feasible_action_mapping_scale", "feasible_action_mapping_gap",
        "base", "nominal_control", "ancillary",
        "reward", "economic_cost", "economic_reward", "projection_penalty",
        "mapping_penalty",
        "move_penalty", "safety_penalty", "state_excess_squared",
        "input_excess_squared", "rpi_excess_squared",
        "violation", "rpi_violation", "projection_gap",
        "candidate", "nominal", "error", "effective_w",
    ]
    return {key: np.asarray([record[key] for record in records]) for key in keys}


